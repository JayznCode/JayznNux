# 0. 진행 상황 변수 (0이면 미완료, 1이면 완료)
task1 = 0
task2 = 0

# 1. 화면 출력
print("=== 파이썬 공부 체크리스트 ===")
print("1. 변수와 조건문 (완료 여부:", task1, ")")
print("2. 파일 입출력   (완료 여부:", task2, ")")

# 2. 사용자 입력받기
num = input("완료한 번호를 입력하세요 (1 또는 2): ")

# 3. 입력에 따른 상태 변경
if num == "1":
    task1 = 1
    print("1번 변수와 조건문 완료 처리되었습니다!")
elif num == "2":
    task2 = 1
    print("2번 파일 입출력 완료 처리되었습니다!")
else:
    print("잘못된 번호입니다.")
